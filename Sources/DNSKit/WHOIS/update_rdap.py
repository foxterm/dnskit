from datetime import datetime
import http.client
import json
import os

RDAP_DATABASE_URL = "https://data.iana.org/rdap/dns.json"


def get_rdap_services():
    connection = http.client.HTTPSConnection("data.iana.org")
    connection.request("GET", "/rdap/dns.json")
    response = connection.getresponse()

    if response.status != 200:
        print("Unable to fetch {}: HTTP {}".format(RDAP_DATABASE_URL, response.status))
        raise "unable to fetch RDAP database"

    data = json.loads(response.read().decode())

    services = {}

    for service in data["services"]:
        if len(service) < 2:
            continue

        tlds = service[0]
        urls = service[1]

        if len(urls) == 0:
            print("No URL for TLDs: {}".format(tlds))
            continue

        base_url = urls[0]

        # Apple platforms enforce App Transport Security, which blocks
        # cleartext HTTP by default. The registries that publish an http://
        # endpoint also serve the same content over https://, so upgrade
        # the scheme to keep lookups working on iOS/macOS without requiring
        # apps to opt-out of ATS.
        if base_url.startswith("http://"):
            base_url = "https://" + base_url[len("http://"):]

        for tld in tlds:
            if tld in services and services[tld] != base_url:
                print("Duplicate TLD {} with different URLs: {} and {}".format(tld, services[tld], base_url))
                continue

            services[tld] = base_url

    return services


